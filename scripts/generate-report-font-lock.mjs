// Generates src/assets/fonts/report-font-lock/index.css (2026-11-16, report consistency).
// The report MASTER CSS names fonts that are NOT bundled (Pretendard, "Noto Sans KR", Georgia, "Times New Roman",
// NanumMyeongjo, Montserrat). Each device then substituted its own installed font (iPhone: Apple SD Gothic / Times,
// Windows: Malgun Gothic / Georgia, the server: WenQuanYi / Liberation Serif), so the same report looked different.
// This file maps those family names, for the report pages only, to bundled files: sans names -> Noto Sans KR Variable
// (already bundled), serif names -> Tinos (metric-compatible with Times; the same design as the Liberation Serif in the
// approved 2026-11-12 sample PDF) with Noto Sans KR for Korean on the next name in the stack, and symbols (✓ △ ○ ① …) -> Noto Sans Symbols 2.
// The MASTER CSS is not edited; only which file each declared family name loads is fixed. Run after font updates:
//   node scripts/generate-report-font-lock.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const NOTO = readFileSync('src/assets/fonts/noto-sans-kr/index.css', 'utf8');
const notoFaces = [...NOTO.matchAll(/@font-face\s*{([^}]*)}/g)].map((m) => {
  const body = m[1];
  const file = /url\(\.\/files\/([^)]+)\)/.exec(body)[1];
  const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1].trim() || '';
  return { file, range };
});
if (notoFaces.length < 100) throw new Error(`Noto Sans KR faces not found (${notoFaces.length})`);

const SYMBOLS_RANGE = 'U+2190-2199,U+2460-24FF,U+25A0-27BF,U+2B00-2BFF';
const TINOS_RANGE = {
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF',
};

const face = (family, src, range, { weight = '100 900', style = 'normal', format = 'woff2-variations' } = {}) =>
  `@font-face{font-family:'${family}';font-style:${style};font-display:block;font-weight:${weight};src:url(${src}) format('${format}');unicode-range:${range}}`;
const symbols = (family) => face(family, './files/noto-sans-symbols-2-symbols-400-normal.woff2', SYMBOLS_RANGE, { weight: '100 900', format: 'woff2' });

const out = [
  '/* GENERATED by scripts/generate-report-font-lock.mjs — do not edit by hand. Report pages only. */',
  '/* Licenses: Noto Sans KR, Noto Sans Symbols 2, Tinos — SIL Open Font License 1.1 (LICENSE-* files). */',
];
// Symbols first: a face declared later wins for overlapping ranges, and Noto KR also has some of these glyphs.
for (const family of ['Noto Sans KR Variable']) out.push(symbols(family));
for (const family of ['Pretendard', 'Noto Sans KR', 'Montserrat']) {
  out.push(symbols(family));
  for (const { file, range } of notoFaces) out.push(face(family, `../noto-sans-kr/files/${file}`, range));
}
// Serif stacks are Georgia,"NanumMyeongjo",serif / Georgia,"Times New Roman",serif. Chrome picks ONE weight/style
// descriptor group per family before unicode-range, so Tinos (400/700, normal/italic) and the variable Noto faces
// (100-900) cannot share a family: Korean would skip to the system font. Georgia therefore carries Latin only (Tinos);
// the second names carry Korean + symbols (Noto, one descriptor group). Latin never reaches them because Georgia has it.
for (const subset of ['latin-ext', 'latin']) for (const weight of [400, 700]) for (const style of ['normal', 'italic']) {
  out.push(face('Georgia', `./files/tinos-${subset}-${weight}-${style}.woff2`, TINOS_RANGE[subset], { weight: String(weight), style, format: 'woff2' }));
}
for (const family of ['Times New Roman', 'NanumMyeongjo']) {
  out.push(symbols(family));
  for (const { file, range } of notoFaces) out.push(face(family, `../noto-sans-kr/files/${file}`, range));
}
writeFileSync('src/assets/fonts/report-font-lock/index.css', `${out.join('\n')}\n`);
console.log(`report-font-lock: ${out.length - 2} @font-face rules`);
